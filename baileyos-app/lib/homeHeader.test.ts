import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

test('the public map header does not show the steward mark and links to Question #001', () => {
  const src = readFileSync(new URL('../components/MapHome.tsx', import.meta.url), 'utf8');
  assert.equal(src.includes('81ABSCS81'), false);
  assert.equal(src.includes('⊞'), false);
  assert.equal(src.includes('The bearing stays'), false);
  assert.match(src, /SWAGG Consulting/);
  assert.match(src, /Answer Question #001/);
  assert.match(src, /href="\/brew\/q\/001"/);
  assert.match(src, /Nothing is saved until you tap Share my place/);
  assert.match(src, /Continue without signing in/);
  assert.match(src, /CHECKIN_RETURN/);
  assert.match(src, /useState\(false\)/);
  assert.match(src, /Your place is already counted/);
  assert.match(src, /3 different phones/);
  assert.match(src, /Phones on this map/);
  const signIn = src.indexOf('Sign in with 360° Brewing');
  const headline = src.indexOf('Show up. Get placed.');
  assert.ok(signIn > 0 && headline > signIn);
  assert.match(src, /sticky top-0/);
  assert.match(src, /suiteSignedIn \? <SuiteIdentity/);
  assert.match(src, /MAP_RETURN/);
  assert.match(src, /cache: 'no-store'/);
  const placements = readFileSync(new URL('../app/api/placements/route.ts', import.meta.url), 'utf8');
  assert.match(placements, /no-store/);
  assert.equal(placements.includes('s-maxage'), false);
});
