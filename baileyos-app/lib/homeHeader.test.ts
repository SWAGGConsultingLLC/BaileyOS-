import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

test('the public map header does not show the steward mark and links to Question #001', () => {
  const src = readFileSync(new URL('../components/MapHome.tsx', import.meta.url), 'utf8');
  assert.equal(src.includes('81ABSCS81'), false);
  assert.equal(src.includes('⊞'), false);
  assert.equal(src.includes('The bearing stays'), false);
  assert.match(src, /SWAGG Consulting/);
  assert.match(src, /Answer Question #001/);
  assert.match(src, /href="\/brew\/q\/001"/);
  assert.match(src, /Nothing is saved until you sign in and tap Share my place/);
  assert.equal(src.includes('Continue without signing in'), false);
  assert.match(src, /CHECKIN_RETURN/);
  assert.match(src, /Show my name and photo/);
  assert.match(src, /Remove my name and photo/);
  assert.match(src, /People on this map/);
  assert.match(src, /neighborhood you have checked into/);
  assert.match(src, /Logged-out visitors see no pins/);
  assert.equal(src.includes('Phones on this map'), false);
  assert.equal(src.includes('3 different phones'), false);
  assert.equal(src.includes('three phones'), false);
  const signIn = src.indexOf('Sign in with 360° Brewing');
  const headline = src.indexOf('Show up. Get placed.');
  assert.ok(signIn > 0 && headline > signIn);
  assert.match(src, /sticky top-0/);
  assert.match(src, /suiteSignedIn \? <SuiteIdentity/);
  assert.match(src, /MAP_RETURN/);
  const map = src.indexOf('<MapView');
  const footer = src.indexOf('BaileyOS is a');
  assert.ok(map > 0 && footer > map);
  assert.match(src, /href="https:\/\/www\.swaggconsulting\.com"/);
  assert.match(src, /target="_blank"/);
  assert.match(src, /rel="noopener noreferrer"/);
  assert.equal(src.includes('fixed bottom'), false);
  assert.match(src, /cache: 'no-store'/);
  const placements = readFileSync(new URL('../app/api/placements/route.ts', import.meta.url), 'utf8');
  assert.match(placements, /no-store/);
  assert.equal(placements.includes('s-maxage'), false);
});
