import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';

test('the public map header does not show the steward mark and links to Question #001', () => {
  const src = readFileSync(new URL('../components/MapHome.tsx', import.meta.url), 'utf8');
  assert.equal(src.includes('81ABSCS81'), false);
  assert.equal(src.includes('⊞'), false);
  assert.equal(src.includes('The bearing stays'), false);
  assert.match(src, /SWAGG Consulting/);
  assert.match(src, /Answer Question #001/);
  assert.match(src, /href="\/brew\/q\/001"/);
  assert.match(src, /Nothing is saved until you tap Share my place/);
  assert.match(src, /Continue without signing in/);
  assert.match(src, /CHECKIN_RETURN/);
  assert.match(src, /useState\(false\)/);
  assert.match(src, /Your place is already counted/);
  assert.match(src, /3 different phones/);
  assert.match(src, /Phones on this map/);
  const signIn = src.indexOf('Check in with LinkedIn');
  const headline = src.indexOf('Show up. Get placed.');
  assert.ok(signIn > 0 && headline > signIn);
  assert.match(src, /#0A66C2/);
  assert.match(src, /Sign in to drop your pin/);
  assert.match(src, /Use email instead/);
  assert.match(src, /aria-label="Check in with LinkedIn"/);
  assert.match(src, /BrewLockup/);
  const lockup = readFileSync(new URL('../components/BrewLockup.tsx', import.meta.url), 'utf8');
  assert.match(lockup, /Our principle/);
  assert.match(lockup, /BREWING_PLACE_LINE/);
  assert.match(lockup, /href=\{MISSION_PATH\}/);
  const nest = readFileSync(new URL('../components/data-nest/DataNestApp.tsx', import.meta.url), 'utf8');
  assert.match(nest, /360° Brewing: sign in to Data Nest/);
  assert.match(nest, /LinkedIn sign-in coming soon, use email/);
  assert.match(nest, /Sign in with LinkedIn/);
  assert.match(src, /LinkedIn sign-in coming soon, use email/);
  assert.match(src, /sticky top-0/);
  assert.match(src, /suiteSignedIn \? <SuiteIdentity/);
  assert.match(src, /MAP_RETURN/);
  const map = src.indexOf('<MapView');
  const footer = src.indexOf('BaileyOS is a');
  assert.ok(map > 0 && footer > map);
  assert.match(src, /href="https:\/\/www\.swaggconsulting\.com"/);
  assert.match(src, /target="_blank"/);
  assert.match(src, /rel="noopener noreferrer"/);
  assert.equal(src.includes('fixed bottom'), false);
  assert.match(src, /cache: 'no-store'/);
  const placements = readFileSync(new URL('../app/api/placements/route.ts', import.meta.url), 'utf8');
  assert.match(placements, /no-store/);
  assert.equal(placements.includes('s-maxage'), false);
});
